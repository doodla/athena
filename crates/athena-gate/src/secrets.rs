//! Secret scanning with gitleaks (design §7.4 check 1, D17, D38).
//!
//! gitleaks always runs with flags that stop the scanned content from relaxing the scan (E17):
//!
//! - `--config` names a file Athena generates from the `[secrets]` section of the judging configuration. It
//!   extends gitleaks' default rules with the reviewed allow-list entries, so a `.gitleaks.toml` committed in
//!   the repository is never read;
//! - `--gitleaks-ignore-path` names an empty directory Athena controls. gitleaks also reads a
//!   `.gitleaksignore` from the directory it scans, so Athena always scans commits through the repository's
//!   git directory, never its work tree, and runs gitleaks from an empty directory. Staged changes are
//!   scanned as a temporary commit object built from the index;
//! - `--ignore-gitleaks-allow` disables inline `gitleaks:allow` markers;
//! - `--max-decode-depth=5` is pinned explicitly.
//!
//! A false positive is handled by committing its allow-list entry first; it governs only later commits.

use crate::{GateError, Result, Rule, Violation};
use athena_data::Config;
use athena_data::config::SecretAllow;
use athena_git::Git;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::{LazyLock, Mutex};

/// One finding, as gitleaks reports it (only the fields Athena uses; author and email are never read).
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct Finding {
    #[serde(rename = "RuleID")]
    pub rule: String,
    #[serde(rename = "Secret")]
    pub secret: String,
    #[serde(rename = "File", default)]
    pub file: String,
    #[serde(rename = "Commit", default)]
    pub commit: String,
    #[serde(rename = "StartLine", default)]
    pub line: u64,
}

/// A ready-to-run gitleaks with Athena's generated configuration.
#[derive(Debug)]
pub struct Gitleaks {
    bin: PathBuf,
    dir: tempfile::TempDir,
    /// SHA-256 of the generated configuration text, part of the key of a remembered text scan.
    config_digest: String,
}

#[derive(Serialize)]
struct GeneratedConfig {
    title: String,
    extend: Extend,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    allowlists: Vec<GeneratedAllow>,
}

#[derive(Serialize)]
struct Extend {
    #[serde(rename = "useDefault")]
    use_default: bool,
}

#[derive(Serialize)]
struct GeneratedAllow {
    description: String,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    paths: Vec<String>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    regexes: Vec<String>,
}

/// The gitleaks configuration Athena generates from a `[secrets]` allow-list.
pub fn generated_config(allowlist: &[SecretAllow]) -> String {
    let config = GeneratedConfig {
        title: "Generated by Athena from athena.toml [secrets]; extends the gitleaks defaults"
            .into(),
        extend: Extend { use_default: true },
        allowlists: allowlist
            .iter()
            .filter(|a| !a.paths.is_empty() || !a.regexes.is_empty())
            .map(|a| GeneratedAllow {
                description: a.description.clone(),
                paths: a.paths.clone(),
                regexes: a.regexes.clone(),
            })
            .collect(),
    };
    toml::to_string(&config).expect("the generated configuration serializes")
}

/// Where the pinned gitleaks lives. `ATHENA_GITLEAKS` overrides it, for adopters who install it elsewhere.
pub fn gitleaks_path(config: &Config) -> PathBuf {
    match std::env::var_os("ATHENA_GITLEAKS").filter(|v| !v.is_empty()) {
        Some(path) => PathBuf::from(path),
        None => athena_data::paths::tool_path("gitleaks", &config.tools.gitleaks.version),
    }
}

impl Gitleaks {
    /// Prepares gitleaks for `config`; fails closed when the pinned binary is missing.
    pub fn new(config: &Config) -> Result<Gitleaks> {
        let bin = gitleaks_path(config);
        if !bin.is_file() {
            return Err(GateError::GitleaksMissing {
                version: config.tools.gitleaks.version.clone(),
                path: bin.display().to_string(),
            });
        }
        Gitleaks::at(bin, &generated_config(&config.secrets.allowlist))
    }

    /// A gitleaks at `bin` with the generated configuration text `config`.
    fn at(bin: PathBuf, config: &str) -> Result<Gitleaks> {
        let dir = tempfile::Builder::new()
            .prefix("athena-gitleaks-")
            .tempdir()?;
        std::fs::write(dir.path().join("config.toml"), config)?;
        std::fs::create_dir(dir.path().join("ignore"))?;
        Ok(Gitleaks {
            bin,
            dir,
            config_digest: athena_data::sha256_hex(config.as_bytes()),
        })
    }

    fn command(&self, mode: &str) -> Command {
        let mut cmd = Command::new(&self.bin);
        // An empty working directory, so no `.gitleaksignore` or `.gitleaks.toml` is found beside it, and
        // no git location variable from a hook environment redirects gitleaks' own git calls.
        cmd.current_dir(self.dir.path().join("ignore"));
        for (key, _) in std::env::vars_os() {
            if key.to_string_lossy().starts_with("GIT_") {
                cmd.env_remove(&key);
            }
        }
        cmd.arg(mode)
            .arg("--no-banner")
            .arg("--no-color")
            .arg("--log-level=error")
            .arg("--config")
            .arg(self.dir.path().join("config.toml"))
            .arg("--gitleaks-ignore-path")
            .arg(self.dir.path().join("ignore"))
            .arg("--ignore-gitleaks-allow")
            .arg("--max-decode-depth=5")
            .arg("--exit-code=0")
            .arg("--report-format=json")
            .arg("--report-path")
            .arg(self.dir.path().join("report.json"))
            .env_remove("GITLEAKS_CONFIG")
            .env_remove("GITLEAKS_CONFIG_TOML");
        cmd
    }

    fn run(&self, mut cmd: Command, stdin: Option<&[u8]>) -> Result<Vec<Finding>> {
        let report = self.dir.path().join("report.json");
        let _ = std::fs::remove_file(&report);
        let out = athena_git::output_with_stdin(&mut cmd, stdin).map_err(|e| {
            GateError::Gitleaks(format!("could not run {}: {e}", self.bin.display()))
        })?;
        if !out.status.success() {
            return Err(GateError::Gitleaks(format!(
                "exit {:?}: {}",
                out.status.code(),
                String::from_utf8_lossy(&out.stderr).trim()
            )));
        }
        let text = std::fs::read_to_string(&report).unwrap_or_else(|_| "[]".into());
        serde_json::from_str(&text)
            .map_err(|e| GateError::Gitleaks(format!("unreadable report: {e}")))
    }

    /// Scans the staged changes (the `pre-commit` hook) as a temporary commit object built from the index.
    pub fn scan_staged(&self, git: &Git) -> Result<Vec<Finding>> {
        let tree = git.write_index_tree()?;
        let head = git.head()?;
        let parents: Vec<&str> = head.iter().map(String::as_str).collect();
        let identity = git
            .clone()
            .with_env("GIT_AUTHOR_NAME", "Athena gate")
            .with_env("GIT_AUTHOR_EMAIL", "noreply@example.invalid")
            .with_env("GIT_COMMITTER_NAME", "Athena gate")
            .with_env("GIT_COMMITTER_EMAIL", "noreply@example.invalid");
        let temporary = identity.commit_tree(
            &tree,
            &parents,
            "staged changes, scanned by the Athena gate\n",
            false,
        )?;
        let range = match head {
            Some(head) => format!("{head}..{temporary}"),
            None => temporary,
        };
        self.scan_log(git, &range)
    }

    /// Scans the commits `git log` selects with `log_opts`, such as `<parent>..<commit>`, through the
    /// repository's git directory.
    pub fn scan_log(&self, git: &Git, log_opts: &str) -> Result<Vec<Finding>> {
        let git_dir = git.common_dir()?;
        let mut cmd = self.command("git");
        cmd.arg(format!("--log-opts={log_opts}")).arg(git_dir);
        self.run(cmd, None)
    }

    /// Scans text, such as an agent's free-text output before it is recorded.
    ///
    /// A text scanned before by the same gitleaks binary (by content) under the same generated configuration
    /// returns the findings of that scan without running gitleaks again: the findings depend on nothing else.
    /// Only successful scans are remembered, so a failing gitleaks still fails every time.
    pub fn scan_text(&self, text: &str) -> Result<Vec<Finding>> {
        let key = binary_digest(&self.bin).map(|binary| {
            athena_data::sha256_hex(
                format!(
                    "{binary}\n{}\n{}",
                    self.config_digest,
                    athena_data::sha256_hex(text.as_bytes())
                )
                .as_bytes(),
            )
        });
        if let Some(key) = &key
            && let Some(found) = SCAN_MEMO.get(key)
        {
            return Ok(found);
        }
        let found = self.run(self.command("stdin"), Some(text.as_bytes()))?;
        if let Some(key) = key {
            SCAN_MEMO.put(key, found.clone());
        }
        Ok(found)
    }
}

/// The most text scans remembered at once; the memory is emptied when it fills.
const MEMO_CAP: usize = 1024;

/// Findings of earlier text scans, keyed by a digest of the binary, the configuration and the text, so the
/// scanned text itself (which may hold a secret) is never kept.
struct Memo {
    cap: usize,
    map: Mutex<HashMap<String, Vec<Finding>>>,
}

impl Memo {
    fn new(cap: usize) -> Memo {
        Memo {
            cap,
            map: Mutex::new(HashMap::new()),
        }
    }

    fn get(&self, key: &str) -> Option<Vec<Finding>> {
        let map = self.map.lock().unwrap_or_else(|e| e.into_inner());
        map.get(key).cloned()
    }

    fn put(&self, key: String, found: Vec<Finding>) {
        let mut map = self.map.lock().unwrap_or_else(|e| e.into_inner());
        if map.len() >= self.cap {
            map.clear();
        }
        map.insert(key, found);
    }

    #[cfg(test)]
    fn len(&self) -> usize {
        self.map.lock().unwrap_or_else(|e| e.into_inner()).len()
    }
}

static SCAN_MEMO: LazyLock<Memo> = LazyLock::new(|| Memo::new(MEMO_CAP));

/// What identifies a file's state without reading it: inode, size, and modification and change times.
type Stamp = (u64, u64, i64, i64, i64, i64);

static BINARIES: LazyLock<Mutex<HashMap<PathBuf, (Stamp, String)>>> =
    LazyLock::new(|| Mutex::new(HashMap::new()));

fn stamp_of(path: &Path) -> Option<Stamp> {
    use std::os::unix::fs::MetadataExt;
    let m = std::fs::metadata(path).ok()?;
    Some((
        m.ino(),
        m.len(),
        m.mtime(),
        m.mtime_nsec(),
        m.ctime(),
        m.ctime_nsec(),
    ))
}

/// SHA-256 of the binary's content. It is computed once per path and again whenever the file's inode, size,
/// modification time or change time differs; a file that cannot be read has no digest, and its scans are not
/// remembered.
fn binary_digest(path: &Path) -> Option<String> {
    let stamp = stamp_of(path)?;
    {
        let known = BINARIES.lock().unwrap_or_else(|e| e.into_inner());
        if let Some((seen, digest)) = known.get(path)
            && *seen == stamp
        {
            return Some(digest.clone());
        }
    }
    let digest = athena_data::sha256_hex(&std::fs::read(path).ok()?);
    // The file may have changed while it was read; a digest without a settled stamp is not kept.
    if stamp_of(path)? == stamp {
        BINARIES
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .insert(path.to_path_buf(), (stamp, digest.clone()));
    }
    Some(digest)
}

fn violations(findings: Vec<Finding>, commit: Option<&str>) -> Vec<Violation> {
    findings
        .into_iter()
        .map(|f| {
            let at = if f.commit.is_empty() { commit.map(str::to_string) } else { Some(f.commit.clone()) };
            Violation::new(
                Rule::Secrets,
                format!("gitleaks rule {} matched {} line {}", f.rule, f.file, f.line),
                "remove the secret (and revoke it if it was real); for a reviewed false positive, commit an \
                 entry in athena.toml [secrets] first",
            )
            .at_path(f.file)
            .in_commit(at.as_deref())
        })
        .collect()
}

/// Secrets in the staged changes (the `pre-commit` hook), under the parent's `[secrets]`.
pub fn check_staged(git: &Git, config: &Config) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    // The findings name the temporary scan commit, which the user never sees; report the staged change.
    let findings = gitleaks
        .scan_staged(git)?
        .into_iter()
        .map(|f| Finding {
            commit: String::new(),
            ..f
        })
        .collect();
    Ok(violations(findings, None))
}

/// Secrets in one commit, under its parent's `[secrets]` (Athena's in-process gate).
pub fn check_commit(
    git: &Git,
    config: &Config,
    parent: Option<&str>,
    commit: &str,
) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    let range = match parent {
        Some(parent) => format!("{parent}..{commit}"),
        None => commit.to_string(),
    };
    Ok(violations(gitleaks.scan_log(git, &range)?, Some(commit)))
}

/// Secrets anywhere in the history reachable from `rev`, under `HEAD`'s `[secrets]` (CI).
pub fn check_history(git: &Git, config: &Config, rev: &str) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    Ok(violations(gitleaks.scan_log(git, rev)?, None))
}

