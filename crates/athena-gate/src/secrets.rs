//! Secret scanning with gitleaks (design §7.4 check 1, D17, D38).
//!
//! gitleaks always runs with flags that stop the scanned content from relaxing the scan (E17):
//!
//! - `--config` names a file Athena generates from the `[secrets]` section of the judging configuration. It
//!   extends gitleaks' default rules with the reviewed allow-list entries, so a `.gitleaks.toml` committed in
//!   the repository is never read;
//! - `--gitleaks-ignore-path` names an empty directory Athena controls. gitleaks also reads a
//!   `.gitleaksignore` from the directory it scans, so Athena always scans commits through the repository's
//!   git directory, never its work tree, and runs gitleaks from an empty directory. Staged changes are
//!   scanned as a temporary commit object built from the index;
//! - `--ignore-gitleaks-allow` disables inline `gitleaks:allow` markers;
//! - `--max-decode-depth=5` is pinned explicitly.
//!
//! A false positive is handled by committing its allow-list entry first; it governs only later commits.

use crate::{GateError, Result, Rule, Violation};
use athena_data::Config;
use athena_data::config::SecretAllow;
use athena_git::Git;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::path::PathBuf;
use std::process::Command;
use std::sync::Mutex;

/// One finding, as gitleaks reports it (only the fields Athena uses; author and email are never read).
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct Finding {
    #[serde(rename = "RuleID")]
    pub rule: String,
    #[serde(rename = "Secret")]
    pub secret: String,
    #[serde(rename = "File", default)]
    pub file: String,
    #[serde(rename = "Commit", default)]
    pub commit: String,
    #[serde(rename = "StartLine", default)]
    pub line: u64,
}

/// A ready-to-run gitleaks with Athena's generated configuration.
#[derive(Debug)]
pub struct Gitleaks {
    bin: PathBuf,
    dir: tempfile::TempDir,
}

#[derive(Serialize)]
struct GeneratedConfig {
    title: String,
    extend: Extend,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    allowlists: Vec<GeneratedAllow>,
}

#[derive(Serialize)]
struct Extend {
    #[serde(rename = "useDefault")]
    use_default: bool,
}

#[derive(Serialize)]
struct GeneratedAllow {
    description: String,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    paths: Vec<String>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    regexes: Vec<String>,
}

/// The gitleaks configuration Athena generates from a `[secrets]` allow-list.
pub fn generated_config(allowlist: &[SecretAllow]) -> String {
    let config = GeneratedConfig {
        title: "Generated by Athena from athena.toml [secrets]; extends the gitleaks defaults"
            .into(),
        extend: Extend { use_default: true },
        allowlists: allowlist
            .iter()
            .filter(|a| !a.paths.is_empty() || !a.regexes.is_empty())
            .map(|a| GeneratedAllow {
                description: a.description.clone(),
                paths: a.paths.clone(),
                regexes: a.regexes.clone(),
            })
            .collect(),
    };
    toml::to_string(&config).expect("the generated configuration serializes")
}

/// Where the pinned gitleaks lives. `ATHENA_GITLEAKS` overrides it, for adopters who install it elsewhere.
pub fn gitleaks_path(config: &Config) -> PathBuf {
    match std::env::var_os("ATHENA_GITLEAKS").filter(|v| !v.is_empty()) {
        Some(path) => PathBuf::from(path),
        None => athena_data::paths::tool_path("gitleaks", &config.tools.gitleaks.version),
    }
}

impl Gitleaks {
    /// Prepares gitleaks for `config`; fails closed when the pinned binary is missing.
    pub fn new(config: &Config) -> Result<Gitleaks> {
        let bin = gitleaks_path(config);
        if !bin.is_file() {
            return Err(GateError::GitleaksMissing {
                version: config.tools.gitleaks.version.clone(),
                path: bin.display().to_string(),
            });
        }
        let dir = tempfile::Builder::new()
            .prefix("athena-gitleaks-")
            .tempdir()?;
        std::fs::write(
            dir.path().join("config.toml"),
            generated_config(&config.secrets.allowlist),
        )?;
        std::fs::create_dir(dir.path().join("ignore"))?;
        Ok(Gitleaks { bin, dir })
    }

    fn command(&self, mode: &str) -> Command {
        let mut cmd = Command::new(&self.bin);
        // An empty working directory, so no `.gitleaksignore` or `.gitleaks.toml` is found beside it, and
        // no git location variable from a hook environment redirects gitleaks' own git calls.
        cmd.current_dir(self.dir.path().join("ignore"));
        for (key, _) in std::env::vars_os() {
            if key.to_string_lossy().starts_with("GIT_") {
                cmd.env_remove(&key);
            }
        }
        cmd.arg(mode)
            .arg("--no-banner")
            .arg("--no-color")
            .arg("--log-level=error")
            .arg("--config")
            .arg(self.dir.path().join("config.toml"))
            .arg("--gitleaks-ignore-path")
            .arg(self.dir.path().join("ignore"))
            .arg("--ignore-gitleaks-allow")
            .arg("--max-decode-depth=5")
            .arg("--exit-code=0")
            .arg("--report-format=json")
            .arg("--report-path")
            .arg(self.dir.path().join("report.json"))
            .env_remove("GITLEAKS_CONFIG")
            .env_remove("GITLEAKS_CONFIG_TOML");
        cmd
    }

    fn run(&self, mut cmd: Command, stdin: Option<&[u8]>) -> Result<Vec<Finding>> {
        let report = self.dir.path().join("report.json");
        let _ = std::fs::remove_file(&report);
        let out = athena_git::output_with_stdin(&mut cmd, stdin).map_err(|e| {
            GateError::Gitleaks(format!("could not run {}: {e}", self.bin.display()))
        })?;
        if !out.status.success() {
            return Err(GateError::Gitleaks(format!(
                "exit {:?}: {}",
                out.status.code(),
                String::from_utf8_lossy(&out.stderr).trim()
            )));
        }
        let text = std::fs::read_to_string(&report).unwrap_or_else(|_| "[]".into());
        serde_json::from_str(&text)
            .map_err(|e| GateError::Gitleaks(format!("unreadable report: {e}")))
    }

    /// Scans the staged changes (the `pre-commit` hook) as a temporary commit object built from the index.
    pub fn scan_staged(&self, git: &Git) -> Result<Vec<Finding>> {
        let tree = git.write_index_tree()?;
        let head = git.head()?;
        let parents: Vec<&str> = head.iter().map(String::as_str).collect();
        let identity = git
            .clone()
            .with_env("GIT_AUTHOR_NAME", "Athena gate")
            .with_env("GIT_AUTHOR_EMAIL", "noreply@example.invalid")
            .with_env("GIT_COMMITTER_NAME", "Athena gate")
            .with_env("GIT_COMMITTER_EMAIL", "noreply@example.invalid");
        let temporary = identity.commit_tree(
            &tree,
            &parents,
            "staged changes, scanned by the Athena gate\n",
            false,
        )?;
        let range = match head {
            Some(head) => format!("{head}..{temporary}"),
            None => temporary,
        };
        self.scan_log(git, &range)
    }

    /// Scans the commits `git log` selects with `log_opts`, such as `<parent>..<commit>`, through the
    /// repository's git directory.
    pub fn scan_log(&self, git: &Git, log_opts: &str) -> Result<Vec<Finding>> {
        let git_dir = git.common_dir()?;
        let mut cmd = self.command("git");
        cmd.arg(format!("--log-opts={log_opts}")).arg(git_dir);
        self.run(cmd, None)
    }

    /// Scans text, such as an agent's free-text output before it is recorded.
    ///
    /// The result for identical text is remembered for the life of the process (see [`MEMO`]); the key holds
    /// the gitleaks binary and the generated configuration too, so a different allow-list never shares an
    /// entry. Only successful scans are remembered.
    pub fn scan_text(&self, text: &str) -> Result<Vec<Finding>> {
        if text.len() > MEMO_MAX_TEXT {
            return self.scan_text_uncached(text);
        }
        let key = self.memo_key(text);
        if let Some(found) = memo().get(&key) {
            return Ok(found.clone());
        }
        let found = self.scan_text_uncached(text)?;
        let mut map = memo();
        if map.len() >= MEMO_MAX_ENTRIES {
            map.clear();
        }
        map.insert(key, found.clone());
        Ok(found)
    }

    fn scan_text_uncached(&self, text: &str) -> Result<Vec<Finding>> {
        let cmd = self.command("stdin");
        self.run(cmd, Some(text.as_bytes()))
    }

    fn memo_key(&self, text: &str) -> (PathBuf, String, String) {
        let config =
            std::fs::read_to_string(self.dir.path().join("config.toml")).unwrap_or_default();
        (self.bin.clone(), config, text.to_string())
    }
}

/// Texts longer than this are scanned every time, so the memo stays small.
const MEMO_MAX_TEXT: usize = 64 * 1024;
/// The memo is cleared when it reaches this many entries.
const MEMO_MAX_ENTRIES: usize = 256;

type MemoMap = HashMap<(PathBuf, String, String), Vec<Finding>>;

static MEMO: Mutex<Option<MemoMap>> = Mutex::new(None);

/// The process-wide memo of text scans, keyed by (binary, generated configuration, exact text). The findings
/// stay in process memory and are never written out.
fn memo() -> MemoGuard {
    let mut guard = MEMO.lock().unwrap_or_else(|e| e.into_inner());
    guard.get_or_insert_with(HashMap::new);
    MemoGuard(guard)
}

struct MemoGuard(std::sync::MutexGuard<'static, Option<MemoMap>>);

impl std::ops::Deref for MemoGuard {
    type Target = MemoMap;
    fn deref(&self) -> &MemoMap {
        self.0.as_ref().expect("the memo is initialised")
    }
}

impl std::ops::DerefMut for MemoGuard {
    fn deref_mut(&mut self) -> &mut MemoMap {
        self.0.as_mut().expect("the memo is initialised")
    }
}

fn violations(findings: Vec<Finding>, commit: Option<&str>) -> Vec<Violation> {
    findings
        .into_iter()
        .map(|f| {
            let at = if f.commit.is_empty() { commit.map(str::to_string) } else { Some(f.commit.clone()) };
            Violation::new(
                Rule::Secrets,
                format!("gitleaks rule {} matched {} line {}", f.rule, f.file, f.line),
                "remove the secret (and revoke it if it was real); for a reviewed false positive, commit an \
                 entry in athena.toml [secrets] first",
            )
            .at_path(f.file)
            .in_commit(at.as_deref())
        })
        .collect()
}

/// Secrets in the staged changes (the `pre-commit` hook), under the parent's `[secrets]`.
pub fn check_staged(git: &Git, config: &Config) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    // The findings name the temporary scan commit, which the user never sees; report the staged change.
    let findings = gitleaks
        .scan_staged(git)?
        .into_iter()
        .map(|f| Finding {
            commit: String::new(),
            ..f
        })
        .collect();
    Ok(violations(findings, None))
}

/// Secrets in one commit, under its parent's `[secrets]` (Athena's in-process gate).
pub fn check_commit(
    git: &Git,
    config: &Config,
    parent: Option<&str>,
    commit: &str,
) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    let range = match parent {
        Some(parent) => format!("{parent}..{commit}"),
        None => commit.to_string(),
    };
    Ok(violations(gitleaks.scan_log(git, &range)?, Some(commit)))
}

/// Secrets anywhere in the history reachable from `rev`, under `HEAD`'s `[secrets]` (CI).
pub fn check_history(git: &Git, config: &Config, rev: &str) -> Result<Vec<Violation>> {
    let gitleaks = Gitleaks::new(config)?;
    Ok(violations(gitleaks.scan_log(git, rev)?, None))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testutil::*;

    fn config() -> Config {
        crate::builtin_config()
    }

    #[test]
    fn generated_configuration_extends_the_defaults() {
        let text = generated_config(&[SecretAllow {
            description: "a reviewed test fixture".into(),
            paths: vec!["^fixtures/".into()],
            regexes: vec![],
        }]);
        assert!(text.contains("useDefault = true"));
        assert!(text.contains("[[allowlists]]"));
        assert!(text.contains("^fixtures/"));
    }

    #[test]
    fn a_generated_token_in_a_commit_is_found() {
        // M1/M2 (blocks): a commit with a generated token.
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        let parent = git.head().unwrap().unwrap();
        write(
            dir.path(),
            &[(
                "src/config.rs",
                &format!("let auth = \"{}\";\n", fake_token()),
            )],
        );
        let commit = commit(&git, "add config\n\nAthena-Job: bootstrap\n");
        let found = check_commit(&git, &config(), Some(&parent), &commit).unwrap();
        assert_eq!(found.len(), 1, "{found:?}");
        assert_eq!(found[0].rule, Rule::Secrets);
    }

    #[test]
    fn content_cannot_relax_the_scan() {
        // M1 (blocks): a token with an allow-list entry, an inline marker, and an ignore file, all in the
        // same commit, is still found.
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        let parent = git.head().unwrap().unwrap();
        let marker = ["gitleaks", "allow"].join(":");
        write(
            dir.path(),
            &[
                (
                    "src/config.rs",
                    &format!("let auth = \"{}\"; // {marker}\n", fake_token()),
                ),
                (
                    ".gitleaks.toml",
                    "[extend]\nuseDefault = true\n[[allowlists]]\ndescription = \"x\"\npaths = ['''src/''']\n",
                ),
                (".gitleaksignore", "src/config.rs:github-pat:1\n"),
            ],
        );
        let commit = commit(&git, "relax the scan\n\nAthena-Job: bootstrap\n");
        let found = check_commit(&git, &config(), Some(&parent), &commit).unwrap();
        assert!(!found.is_empty(), "the token must still be found");
    }

    #[test]
    fn a_committed_allow_list_entry_governs_later_commits() {
        // M1 (allows): a commit after its allow-list entry was committed first.
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        let mut config = config();
        config.secrets.allowlist.push(SecretAllow {
            description: "reviewed fixture".into(),
            paths: vec!["^fixtures/".into()],
            regexes: vec![],
        });
        let parent = git.head().unwrap().unwrap();
        write(
            dir.path(),
            &[(
                "fixtures/token.txt",
                &format!("auth = \"{}\"\n", fake_token()),
            )],
        );
        let commit = commit(&git, "fixture\n\nAthena-Job: bootstrap\n");
        assert!(
            check_commit(&git, &config, Some(&parent), &commit)
                .unwrap()
                .is_empty()
        );
    }

    #[test]
    fn a_clean_commit_passes() {
        // M1 (allows): a clean commit.
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        let parent = git.head().unwrap().unwrap();
        write(
            dir.path(),
            &[(
                "src/lib.rs",
                "pub fn add(a: u32, b: u32) -> u32 { a + b }\n",
            )],
        );
        let commit = commit(&git, "clean\n\nAthena-Job: bootstrap\n");
        assert!(
            check_commit(&git, &config(), Some(&parent), &commit)
                .unwrap()
                .is_empty()
        );
    }

    #[test]
    fn staged_tokens_are_found() {
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        write(
            dir.path(),
            &[("notes.txt", &format!("auth: {}\n", fake_token()))],
        );
        git.run(["add", "-A"]).unwrap();
        assert_eq!(check_staged(&git, &config()).unwrap().len(), 1);
    }

    #[test]
    fn a_token_in_history_is_found() {
        // M3 (blocks): a token in an old commit fails the history scan.
        let (dir, git) = repo(&[("README.md", "hello\n")]);
        write(
            dir.path(),
            &[("old.txt", &format!("auth: {}\n", fake_token()))],
        );
        commit(&git, "leak\n\nAthena-Job: bootstrap\n");
        std::fs::remove_file(dir.path().join("old.txt")).unwrap();
        commit(&git, "remove\n\nAthena-Job: bootstrap\n");
        assert!(!check_history(&git, &config(), "HEAD").unwrap().is_empty());
    }

    #[test]
    fn the_text_memo_returns_what_a_fresh_scan_returns_and_never_another_texts() {
        let gitleaks = Gitleaks::new(&config()).unwrap();
        let secret_text = format!("memo test: auth = \"{}\"\n", fake_token());
        let clean_text = "memo test: nothing to see here\n";
        let fresh = gitleaks.scan_text_uncached(&secret_text).unwrap();
        assert!(!fresh.is_empty(), "the token must be found");

        // Identical text twice: both equal the fresh scan (the second comes from the memo).
        assert_eq!(gitleaks.scan_text(&secret_text).unwrap(), fresh);
        assert_eq!(gitleaks.scan_text(&secret_text).unwrap(), fresh);
        // Clean text after secret-bearing text finds nothing, and the secret text still matches.
        assert!(gitleaks.scan_text(clean_text).unwrap().is_empty());
        assert_eq!(gitleaks.scan_text(&secret_text).unwrap(), fresh);

        // A different allow-list (another Gitleaks) does not share entries.
        let mut allowing = config();
        allowing.secrets.allowlist.push(SecretAllow {
            description: "memo test".into(),
            paths: vec![],
            regexes: vec![".*".into()],
        });
        let allowing = Gitleaks::new(&allowing).unwrap();
        let expected = allowing.scan_text_uncached(&secret_text).unwrap();
        assert_eq!(allowing.scan_text(&secret_text).unwrap(), expected);
        assert_eq!(gitleaks.scan_text(&secret_text).unwrap(), fresh);
    }

    #[test]
    fn a_missing_gitleaks_fails_closed() {
        let mut config = config();
        config.tools.gitleaks.version = "0.0.0-not-installed".into();
        if std::env::var_os("ATHENA_GITLEAKS").is_none() {
            assert!(matches!(
                Gitleaks::new(&config),
                Err(GateError::GitleaksMissing { .. })
            ));
        }
    }
}
